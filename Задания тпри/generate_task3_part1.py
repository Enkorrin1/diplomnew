def add_formula_stp(doc, formula_str, formula_num_str):
    """Добавляет аккуратную формулу с номером справа по СТП 01-2017"""
    tbl = doc.add_table(rows=1, cols=2)
    tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
    tbl.autofit = False
    
    for r in tbl.rows:
        for c in r.cells:
            c.width = Cm(8.5)
            
    p0 = tbl.rows[0].cells[0].paragraphs[0]
    p0.alignment = WD_ALIGN_PARAGRAPH.LEFT
    p0.paragraph_format.first_line_indent = Cm(1.25)
    p0.paragraph_format.line_spacing = 1.5
    p0.paragraph_format.space_before = Pt(6)
    p0.paragraph_format.space_after = Pt(4)
    r0 = p0.add_run(formula_str)
    r0.font.name = 'Times New Roman'
    r0.font.size = Pt(14)
    r0.italic = True
    
    p1 = tbl.rows[0].cells[1].paragraphs[0]
    p1.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    p1.paragraph_format.first_line_indent = Cm(0)
    p1.paragraph_format.line_spacing = 1.5
    p1.paragraph_format.space_before = Pt(6)
    p1.paragraph_format.space_after = Pt(4)
    r1 = p1.add_run(formula_num_str)
    r1.font.name = 'Times New Roman'
    r1.font.size = Pt(14)

